def main(sample_path: Path, out_path: Path) -> None:
    rows = [json.loads(line) for line in sample_path.read_text(encoding="utf-8").splitlines()]
    if len(rows) != len(RESULTS):
        raise SystemExit(f"표본 {len(rows)}건, 추출 {len(RESULTS)}건 - 개수 불일치")
    with out_path.open("w", encoding="utf-8") as f:
        for row, result in zip(rows, RESULTS, strict=True):
            extracted = Extracted(service_id=row["service_id"], source=row["source"], model="claude-code-session", result=result)
            f.write(extracted.model_dump_json() + "\n")
    print(f"{len(RESULTS)}건 저장: {out_path}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))

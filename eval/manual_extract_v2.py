def P(label: str, ev: list[str], benefit: str | None = None, **cond: object) -> EligibilityPath:
    conditions = Conditions.model_validate(EMPTY.model_dump() | cond)
    return EligibilityPath(label=label, conditions=conditions, benefit=benefit, evidence=ev)


def R(scope: str = "관내", years: float | None = None) -> Residency:
    return Residency.model_validate({"scope": scope, "min_years": years})


def X(kind: str, text: str, ev: str) -> Exclusion:
    return Exclusion.model_validate({"type": kind, "text": text, "evidence": ev})


def D(kind: str = "상시", start: str | None = None, end: str | None = None) -> Deadline:
    return Deadline.model_validate({"type": kind, "start": start, "end": end})


def S(rel: str, paths: list[EligibilityPath], excl: list[Exclusion] | None = None, disc: bool = False,
      und: list[str] | None = None, dl: Deadline | None = None) -> ServiceEligibility:
    return ServiceEligibility.model_validate({
        "elderly_relevance": rel, "paths": [p.model_dump() for p in paths],
        "exclusions": [e.model_dump() for e in excl or []], "discretionary": disc,
        "undecidable": und or [], "deadline": (dl or D()).model_dump(),
    })


